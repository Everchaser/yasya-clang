/*
 * С помощью препроцессорной команды define можно удобно выдать каким-либо сложным значениям опрятные имена
 * Можно использовать для отладки, простенького конфига, или просто для повышения читаемости кода
*/

#include <stdio.h>

#define MIN 8
#define MAX 10

#define DEBUG 1

#define pi 3.14 // типа число пи

int main() {
    if (DEBUG)
        printf("Hello, world!\n");

    for (int i = MIN; i < MAX; i++)
        printf("%d", i);

    printf("\n%f", pi); // при дальнейшем чтении кода будет удобно увидеть не число, а общепринятое название
    return 0;
}
